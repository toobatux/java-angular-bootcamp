public class Hello {
    // Program entry point — JVM starts here when you run `java Hello`
    public static void main(String[] args) {
        // Print one line of text: Hello, JVM! (hint: System.out.println)
        System.out.println("Hello, JVM!");
    }
}

// The compiler translates the program into bytecode,
// which the JVM runs (interprets/JIT compiles) on the target machine